test('手机端：AI 结果先确认再保存，原始照片不进入药箱，账户可退出', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  // This is an explicit transport stub. It tests UI wiring, not real recognition accuracy.
  await page.route('**/api/config', route => route.fulfill({ json: { data: { aiEnabled: true, pushEnabled: false, vapidPublicKey: '' } } }))
  let imageWasSent = false
  await page.route('**/api/recognize', route => {
    imageWasSent = route.request().postDataJSON().image.startsWith('data:image/png;base64,')
    return route.fulfill({ json: { data: { name: '模拟识别药品', specification: '20mg × 12片', expiryDate: '', instructions: '模拟包装文字，仅用于接线测试。', warnings: ['有效期无法确认，请核对包装。'] } } })
  })
  await page.goto('/')
  await page.getByRole('button', { name: '登录 / 注册', exact: true }).click()
  await page.getByRole('button', { name: '免费注册', exact: true }).click()
  await page.getByLabel('你的称呼').fill('手机用户')
  await page.getByLabel('邮箱地址').fill(`mobile-${Date.now()}@example.com`)
  await page.getByLabel('密码', { exact: true }).fill('test-password-2026')
  await page.getByRole('button', { name: '创建账户', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '添加药品', exact: true }).click()
  await page.getByLabel('选择药品图片').setInputFiles('public/icon-192.png')
  await page.getByRole('button', { name: 'AI 识别药品', exact: true }).click()
  await expect(page.getByLabel('药品名称')).toHaveValue('模拟识别药品')
  expect(imageWasSent).toBe(true)
  expect((await (await page.request.get('/api/medications')).json()).data).toHaveLength(0)
  await page.getByLabel('药品名称').fill('用户核对后的药品')
  await page.getByLabel('有效期至').fill('2030-01-01')
  await page.getByRole('button', { name: '设置提醒', exact: true }).click()
  await expect(page.getByLabel('每次用量')).toBeEmpty()
  await page.getByLabel('每次用量').fill('仅测试：1片')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: '确认并保存', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const meds = (await (await page.request.get('/api/medications')).json()).data
  expect(meds).toHaveLength(1)
  expect(meds[0].name).toBe('用户核对后的药品')
  expect(meds[0].image).toBeUndefined()
  await page.getByRole('navigation', { name: '手机导航' }).getByRole('button', { name: '提醒设置' }).click()
  await page.getByRole('button', { name: '退出账户' }).click()
  await expect(page.getByText('正在预览示例空间', { exact: false })).toBeVisible()
})
