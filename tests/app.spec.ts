test('桌面、平板和手机布局及导航无横向溢出', async ({ page }) => {
  for (const width of [1440, 768, 390, 360]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/')
    await expect(page.locator('.welcome-banner')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    if (width === 1440 || width === 390) await page.screenshot({ path: `docs/preview-${width}.png`, fullPage: true })
    const nav = page.getByRole('navigation', { name: width <= 760 ? '手机导航' : '主导航' })
    for (const label of ['我的药箱', '服药记录', '提醒设置']) {
      await nav.getByRole('button', { name: label, exact: true }).click()
      await expect(page.getByRole('heading', { level: 1 })).toContainText(label === '提醒设置' ? '提醒设置' : label)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    }
    await page.getByRole('button', { name: '登录 / 注册', exact: true }).first().click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.getByRole('button', { name: '关闭弹窗' }).click()
  }
})

